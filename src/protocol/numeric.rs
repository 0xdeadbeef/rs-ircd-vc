impl fmt::Display for Numeric {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{:03}", self.0)
    }
}

impl Numeric {
    /// True for replies in the `001`-`399` success range.
    pub fn is_reply(self) -> bool {
        (1..=399).contains(&self.0)
    }

    /// True for replies in the `400`-`599` error range.
    pub fn is_error(self) -> bool {
        (400..=599).contains(&self.0)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn formats_with_leading_zeroes() {
        assert_eq!(Numeric::RPL_WELCOME.to_string(), "001");
        assert_eq!(Numeric::ERR_NEEDMOREPARAMS.to_string(), "461");
    }

    #[test]
    fn classifies_ranges() {
        assert!(Numeric(1).is_reply());
        assert!(Numeric(399).is_reply());
        assert!(Numeric(400).is_error());
        assert!(!Numeric(600).is_error());
    }
}
