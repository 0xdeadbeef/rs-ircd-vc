use std::fmt;

/// A three-digit IRC numeric reply code.
///
/// Wrapping the `u16` in a newtype keeps numeric codes distinct from ordinary
/// port numbers or counts in APIs that take both.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Numeric(pub u16);

macro_rules! numerics {
    ($($name:ident = $code:expr, $doc:literal;)*) => {
        impl Numeric {
            $(
                #[doc = $doc]
                pub const $name: Numeric = Numeric($code);
            )*
        }
    };
}

